# ---- Table S3: threshold sensitivity ----------------------------------------------------------------------
rows3 = list(csv.DictReader(open(os.path.join(CT, "sensitivity", "sensitivity_stage12.tsv")), delimiter="\t"))
base = rows3[0]
fam = {}
for r in rows3[1:]:
    v = r["variant"]
    if ", D1 rule v1" in v:
        continue
    if v.startswith("record twins"):
        key = "record twins"
    elif v.startswith("S6 peptides"):
        key = "S6 peptides"
    else:
        key = v.split(" (published")[0]
        key = key.split(" >=")[0].split(" <")[0] if "rule" not in key and "order" not in key else key.split(":")[0]
    fam.setdefault(key, []).append(r)
PUB = {"D1 rule v1": "pattern + D2 or D3", "RNA verdict order v1": "test first",
       "D1 period identity": "0.6", "D1 rep25": "0.8", "D1-D3 domain guard": "0.05", "D2 non-coding windows": "0.5",
       "D3 open frames": "2", "coding signal Fickett median": "0.95", "spliced reads per intron": "3",
       "'full' intron fraction": "0.9", "'partial' intron fraction": "0.5", "testable-intron flank depth": "10",
       "record twins": "twins not independent", "S6 peptides": "all 5 length fifths"}
TESTED = {"record twins": "counted as independent", "S6 peptides": "3 of 5 fifths"}
LABEL = {"D1 rule v1": "repeat rule: pattern alone a contradiction", "RNA verdict order v1": "RNA verdict order",
         "record twins": "record twins in S1, S2", "S6 peptides": "peptide line S6"}


def rng(rs, col):
    vals = [int(x[col]) for x in rs] + [int(base[col])]
    return f"{min(vals)}--{max(vals)}" if min(vals) != max(vals) else f"{min(vals)}"


t3 = []
for k, rs in fam.items():
    tested = TESTED.get(k) or "; ".join(r["variant"].split(">= ")[-1].split("< ")[-1].split(" (")[0] if "rule" not in k and "order" not in k
                                        else "first version" for r in rs)
    t3.append([tx(LABEL.get(k, k)), tx(PUB.get(k, "")), tx(tested),
               f"{rng(rs, 'all_A')} / {rng(rs, 'all_B')} / {rng(rs, 'all_C')} / {rng(rs, 'all_D')}",
               f"{rng(rs, 'big_A')} / {rng(rs, 'big_B')} / {rng(rs, 'big_C')} / {rng(rs, 'big_D')}",
               f"{max(int(r['sequences_changing_grade']) for r in rs)} ({max(int(r['of_which_above_45212']) for r in rs)})"])
dsens = list(csv.DictReader(open(os.path.join(CT, "dna", "sensitivity.tsv")), delimiter="\t"))
DPUB = {"min_pairs_per_boundary": ("source reads: unique pairs per boundary", "5"),
        "min_unique_depth_illumina": ("source reads: unique depth, testable boundary", "10"),
        "min_frac_depth5": ("source reads: share of bases at depth ≥ 5", "0.99"),
        "max_discordant_frac": ("source reads: discordant pairs per window", "0.10")}
for key, (label, pv) in DPUB.items():
    sets = sorted({r["setting"].split("=")[1] for r in dsens if r["setting"].startswith(key + "=")}, key=float)
    ch = [f"{r['accession']} {r['grade_now']}→{r['grade']} at {r['setting'].split('=')[1]}" for r in dsens
          if r["setting"].startswith(key + "=") and r["grade"] != r["grade_now"]]
    t3.append([tx(label), pv, "; ".join(sets), "\\multicolumn{2}{l}{only the 5 checked sequences can change}",
               tx("; ".join(ch) if ch else "none of the 5")])
write("tableS3_sensitivity.tex", t3)

