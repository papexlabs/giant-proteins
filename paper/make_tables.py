def tx(s):
    s = str(s)
    for a, b in (("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"), ("#", "\\#"), ("_", "\\_"), ("$", "\\$"),
                 (">=", "$\\geq$"), ("<=", "$\\leq$"), ("≥", "$\\geq$"), ("→", "$\\rightarrow$"), ("–", "--"),
                 ("±", "$\\pm$")):
        s = s.replace(a, b)
    return s


def write(name, rows):
    with open(os.path.join(TAB, name), "w") as f:
        f.write("% Generated by paper/make_tables.py. Do not edit.\n")
        f.write("\n".join(" & ".join(r) + " \\\\" for r in rows) + "\n")


def n(x):
    return f"{int(x):,}"


