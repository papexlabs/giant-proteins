def short(v):
    v = v.split(" [")[0]
    for a, b in (("against: copy-number anomaly (v3.1): ", "against, copy number "),
                 ("supported by the reads (short reads; the ", "supported; "), (" repeat block(s) spanned by ", " repeat spanned by "),
                 (" long reads)", " long reads"), ("against: 1 single-copy boundary(ies) with 0 spanning pairs between well-covered windows;"
                                                  " 1 clip pile-up(s) where physical coverage drops; discordant pairs up to 19% in a window",
                                                  "against: 0 spanning pairs, clipped reads, 19 % discordant pairs"),
                 (" (no long reads to resolve it)", ""), ("only 98.7% of single-copy gene bases at depth >= 5", "98.7 % of bases at depth ≥ 5"),
                 (", excess copies (collapsed repeat?)", ""), (", deficit (expanded or absent?)", "")):
        v = v.replace(a, b)
    return v


