"""Tables generated from the repository's files (standard library only).

Writes
  paper/supplementary/Table_S1_leaderboard.tsv  copy of data/leaderboard.tsv (Supplementary Table S1)
  paper/supplementary/Table_S1_columns.tsv      its column dictionary
  paper/tables/tableS1_columns.tex              the dictionary as a LaTeX table body
  paper/tables/tableS2_misassembly.tex          source-read check on known misassemblies (controls/dna)
  paper/tables/tableS3_sensitivity.tex          threshold sensitivity (controls/sensitivity, controls/dna)
  paper/tables/tableS4_repeat_rna.tex           RNA-seq stage of the repeat-flag models
  paper/tables/tableS5_proteomics.tex           the three proteomics searches
The .tex files hold only rows (\\\\ separated); the caption and column format live in supplement.tex.
"""
