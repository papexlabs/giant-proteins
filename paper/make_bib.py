def crossref(doi):
    req = urllib.request.Request("https://api.crossref.org/works/" + doi, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)["message"]


def tex(s):
    s = re.sub(r"\s+", " ", s or "")
    s = re.sub(r"<i>\s*(.*?)\s*</i>", lambda m: "@@I@@" + m.group(1) + "@@J@@", s)
    s = re.sub(r"<[^>]+>", "", s)
    s = s.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
    for a, b in (("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"), ("#", "\\#"), ("_", "\\_")):
        s = s.replace(a, b)
    s = s.replace("@@I@@", "\\textit{").replace("@@J@@", "}").replace("≈", "$\\approx$")
    s = s.replace("“ ", "“").replace(" ”", "”")
    for sp in ("Sycon ciliatum",):                       # species names Crossref gives without markup
        s = s.replace(sp, "\\textit{" + sp + "}") if "\\textit{" + sp not in s else s
    return re.sub(r"\s+", " ", s).strip()


def entry(key, doi, m):
    typ = m.get("type")
    au = m.get("author", [])
    if au and "name" in au[0] and "family" not in au[0]:       # consortium listed first: cite it alone
        au = au[:1]
    names = [tex(f"{a.get('family', a.get('name', ''))}, {a.get('given', '')}".strip(", ")) for a in au]
    if len(names) > 6:                                           # first six, then 'et al.'
        names = names[:6] + ["others"]
    authors = " and ".join("{" + x + "}" if "," not in x and x != "others" else x for x in names)
    year = (m.get("published-print") or m.get("published-online") or m.get("issued"))["date-parts"][0][0]
    f = {"author": authors, "title": "{" + tex(m["title"][0]) + "}", "year": str(year), "doi": doi}
    if typ == "posted-content":
        f["journal"] = "bioRxiv"
        f["note"] = "Preprint"
        kind = "article"
    else:
        kind = "article"
        f["journal"] = tex((m.get("container-title") or [""])[0])
        for a, b in (("volume", "volume"), ("issue", "number"), ("page", "pages")):
            if m.get(a):
                f[b] = tex(m[a]).replace("-", "--")
        if not m.get("page") and m.get("article-number"):
            f["pages"] = tex(m["article-number"])
    body = ",\n".join(f"  {k} = {{{v}}}" for k, v in f.items())
    return f"@{kind}{{{key},\n{body}\n}}\n"


if __name__ == "__main__":
    check = "--check" in sys.argv
    out = []
    for key, doi in REFS:
        m = crossref(doi)
        out.append(entry(key, doi, m))
        print(key, doi, "|", (m.get("title") or [""])[0][:70], "|", (m.get("container-title") or [""])[0][:40])
        time.sleep(1)
    if not check:
        open(os.path.join(HERE, "refs.bib"), "w").write(
            "% Generated by paper/make_bib.py from Crossref records of each DOI (13 Nov 2026). Do not edit by hand.\n\n"
            + "\n".join(out))
